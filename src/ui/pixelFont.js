const W = 5;
const H = 7;
const GAP = 1;

// Draw `text` into `canvas` (created if missing). Options: scale (pixel size),
// color, outline (true = dark border around letters).
export function drawPixelText(canvas, text, { scale = 2, color = '#ffffff', outline = true } = {}) {
  const chars = [...String(text).toUpperCase()];
  const pad = outline ? 1 : 0;
  const width = Math.max(1, chars.length * (W + GAP) - GAP + pad * 2);
  const height = H + pad * 2;
  canvas.width = width;
  canvas.height = height;
  canvas.style.width = `${width * scale}px`;
  canvas.style.height = `${height * scale}px`;
  canvas.style.imageRendering = 'pixelated';
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, width, height);

  const plot = (fill, ox, oy) => {
    ctx.fillStyle = fill;
    chars.forEach((ch, i) => {
      const glyph = GLYPHS[ch] ?? GLYPHS['?'];
      const x0 = pad + i * (W + GAP) + ox;
      for (let y = 0; y < H; y++) {
        for (let x = 0; x < W; x++) if (glyph[y][x] === '#') ctx.fillRect(x0 + x, pad + y + oy, 1, 1);
      }
    });
  };
  if (outline) {
    for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) plot('rgba(10,14,28,0.9)', ox, oy);
  }
  plot(color, 0, 0);
  return canvas;
}

// A canvas element showing pixel text; call .setText() to change it.
export function pixelLabel(text = '', options = {}) {
  const canvas = document.createElement('canvas');
  canvas.className = 'pixel-label';
  let last = null;
  canvas.setText = (t, opts = options) => {
    const key = `${t}|${opts.color}|${opts.scale}`;
    if (key === last) return;
    last = key;
    drawPixelText(canvas, t, { ...options, ...opts });
  };
  canvas.setText(text);
  return canvas;
}
